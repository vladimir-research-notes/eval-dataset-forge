# Printed at the foot of every generated page. Names the tool, not the clock: this file is a
# rendering of a hashed artifact, and a timestamp here would make two renderings of one card
# differ (see DatasetCard's docstring).
FOOTER = "Generated by eval-dataset-forge from manifest.json and audit.json. CPU-only, offline."


def _span(span: Span) -> str:
    if span.kind == CODE:
        return f"<code>{_escape(span.text)}</code>"
    return _escape(span.text)


def inline(text: str) -> str:
    """Render inline text: code spans as ``<code>``, everything else escaped."""
    return "".join(_span(span) for span in inline_spans(text))


def _table(block: Table) -> str:
    head = "".join(f"<th>{inline(header)}</th>" for header in block.headers)
    body = "\n".join(
        "    <tr>" + "".join(f"<td>{inline(value)}</td>" for value in row) + "</tr>"
        for row in block.rows
    )
    caption = f"\n    <caption>{inline(block.caption)}</caption>" if block.caption else ""
    return (
        f"<table>{caption}\n"
        f"    <thead><tr>{head}</tr></thead>\n"
        f"    <tbody>\n{body}\n    </tbody>\n"
        f"  </table>"
    )


def render_block(block: Block) -> str:
    """Render one block as an HTML element. Returns ``""`` for a block with no content."""
    match block:
        case Heading(text=text, level=level):
            return f"<h{level}>{inline(text)}</h{level}>"
        case Paragraph(text=text):
            return f"<p>{inline(text)}</p>"
        case Bullets(items=items):
            if not items:
                return ""
            entries = "\n".join(f"    <li>{inline(item)}</li>" for item in items)
            return f"<ul>\n{entries}\n  </ul>"
        case Note(text=text):
            return f'<aside class="note">{inline(text)}</aside>'
        case Code(text=text, language=language):
            css = f' class="language-{_escape(language)}"' if language else ""
            return f"<pre><code{css}>{_escape(text.rstrip(chr(10)))}</code></pre>"
        case Table():
            return _table(block)
    raise TypeError(f"unknown block type: {type(block).__name__}")


def _plain(text: str) -> str:
    """Escaped text with code spans flattened to their contents.

    ``<title>`` is #PCDATA: a ``<code>`` element inside it is not markup, it is six literal
    characters in the browser tab. The ``<h1>`` gets the full inline rendering.
    """
    return _escape("".join(span.text for span in inline_spans(text)))


def render(document: Document, *, footer: str = FOOTER) -> str:
    """Render ``document`` as a standalone HTML page."""
    body = "\n  ".join(
        rendered for block in document.blocks if (rendered := render_block(block))
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{_plain(document.title)}</title>
<style>
{STYLESHEET}</style>
</head>
<body>
  <h1>{inline(document.title)}</h1>
  {body}
  <footer>{inline(footer)}</footer>
</body>
</html>
"""


def to_bytes(document: Document, *, footer: str = FOOTER) -> bytes:
    """The exact bytes of a rendered HTML artifact. UTF-8, LF, deterministic."""
    return render(document, footer=footer).encode("utf-8")


__all__ = ["FOOTER", "STYLESHEET", "inline", "render", "render_block", "to_bytes"]
