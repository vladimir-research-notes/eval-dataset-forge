"""HTML backend for :class:`~eval_dataset_forge.reports.document.Document` (Milestone 11).

Emits a standalone page: one file, inline stylesheet, no scripts, no fonts, no network. A
dataset card is read by someone deciding whether to trust a benchmark; it should not require
a server, and it should not be able to phone one.

Every literal span goes through :func:`html.escape` with ``quote=True``. That is the whole
security argument, and it is worth stating because the input is not trusted: ``license_notes``,
``recommended_use``, and ``non_goals`` are curator prose, and ``known_issues`` interpolates
example ids that came from a JSONL file someone else wrote. The Markdown backend escapes
``<`` for the same reason. A test drives ``<script>alert(1)</script>`` through both.

The stylesheet is deliberately small and shares the site's palette without importing it: a
card copied out of a release directory has to render on its own, and a ``<link>`` to a
stylesheet that is not there is worse than no stylesheet at all.
"""

from __future__ import annotations

from html import escape as _escape

from eval_dataset_forge.reports.document import (
    CODE,
    Block,
    Bullets,
    Code,
    Document,
    Heading,
    Note,
    Paragraph,
    Span,
    Table,
    inline_spans,
)

